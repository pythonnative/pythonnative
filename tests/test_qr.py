# ── Structure ──────────────────────────────────────────────────────────


def _finder_at(code: qr.QRCode, left: int, top: int) -> bool:
    for dy in range(7):
        for dx in range(7):
            ring = max(abs(dx - 3), abs(dy - 3))
            if code[left + dx, top + dy] != (ring != 2):
                return False
    return True


@pytest.mark.parametrize("version", [1, 2, 7, 14, 40])
def test_function_patterns(version: int) -> None:
    code = qr.encode("structure", version=version, mask=version % 8)
    size = code.size
    assert size == 4 * version + 17
    assert len(code.modules) == size and all(len(row) == size for row in code.modules)
    assert all(isinstance(dark, bool) for row in code.modules for dark in row)
    for left, top in ((0, 0), (size - 7, 0), (0, size - 7)):
        assert _finder_at(code, left, top)
    # Separators around the finders are light.
    for i in range(8):
        assert not code[7, i] and not code[i, 7]
        assert not code[size - 8, i] and not code[size - 1 - i, 7]
        assert not code[7, size - 1 - i] and not code[i, size - 8]
    for i in range(8, size - 8):
        assert code[i, 6] == (i % 2 == 0)
        assert code[6, i] == (i % 2 == 0)
    assert code[8, size - 8]  # The dark module.
    if version > 1:
        # The bottom-right alignment pattern is centered at (size - 7, size - 7).
        center = size - 7
        for dy in range(-2, 3):
            for dx in range(-2, 3):
                assert code[center + dx, center + dy] == (max(abs(dx), abs(dy)) != 1)


def _format_bits(code: qr.QRCode) -> Tuple[int, int]:
    size = code.size
    first = [code[8, i] for i in range(6)] + [code[8, 7], code[8, 8], code[7, 8]]
    first += [code[14 - i, 8] for i in range(9, 15)]
    second = [code[size - 1 - i, 8] for i in range(8)] + [code[8, size - 15 + i] for i in range(8, 15)]
    return sum(bit << i for i, bit in enumerate(first)), sum(bit << i for i, bit in enumerate(second))


@pytest.mark.parametrize(
    "error, mask, expected",
    [
        ("M", 0, 0b101010000010010),
        ("L", 4, 0b110011000101111),
        ("Q", 6, 0b010111011011010),
        ("H", 2, 0b001110011100111),
    ],
)
def test_format_information(error: str, mask: int, expected: int) -> None:
    code = qr.encode("FORMAT", error=error, mask=mask)
    assert _format_bits(code) == (expected, expected)


@pytest.mark.parametrize("version, expected", [(7, 0x07C94), (21, 0x15683), (40, 0x28C69)])
def test_version_information(version: int, expected: int) -> None:
    code = qr.encode("v", version=version, mask=0)
    size = code.size
    bottom_left = sum(code[i // 3, size - 11 + i % 3] << i for i in range(18))
    top_right = sum(code[size - 11 + i % 3, i // 3] << i for i in range(18))
    assert bottom_left == top_right == expected


