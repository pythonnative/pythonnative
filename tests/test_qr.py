# ── Rendering ──────────────────────────────────────────────────────────


def _from_terminal(text: str, border: int, invert: bool) -> List[List[bool]]:
    halves = {"█": (True, True), "▀": (True, False), "▄": (False, True), " ": (False, False)}
    rows: List[List[bool]] = []
    for line in text.split("\n"):
        rows.append([halves[ch][0] for ch in line])
        rows.append([halves[ch][1] for ch in line])
    # Filled means light by default and dark when inverted.
    return [[filled == invert for filled in row[border : -border or None]] for row in rows[border:]]


@pytest.mark.parametrize("border", [0, 1, 2, 4])
@pytest.mark.parametrize("invert", [False, True])
def test_terminal_round_trips(border: int, invert: bool) -> None:
    code = qr.encode(CONNECT_URL)
    text = qr.to_terminal(code, border=border, invert=invert)
    lines = text.split("\n")
    width = code.size + 2 * border
    assert len(lines) == (width + 1) // 2
    assert all(len(line) == width for line in lines)
    assert set(text) <= {"█", "▀", "▄", " ", "\n"}
    decoded = _from_terminal(text, border, invert)
    assert decoded[: code.size] == [list(row) for row in code.modules]


def test_terminal_quiet_zone() -> None:
    code = qr.encode("quiet")
    width = code.size + 4
    lines = qr.to_terminal(code).split("\n")
    # Light modules are filled by default, so the quiet zone is solid.
    assert lines[0] == "█" * width
    assert all(line[:2] == "██" and line[-2:] == "██" for line in lines[:-1])
    # The symbol has an odd height, so the last line's lower half is background.
    assert lines[-1] == "▀" * width
    # The top-left finder corner is dark, drawn as background.
    assert lines[1][2] == " "
    inverted = qr.to_terminal(code, invert=True).split("\n")
    assert inverted[0] == " " * width and inverted[-1] == " " * width
    assert inverted[1][2] == "█"


def test_terminal_rejects_negative_border() -> None:
    with pytest.raises(ValueError):
        qr.to_terminal(qr.encode("x"), border=-1)


SVG = "{http://www.w3.org/2000/svg}"


def test_svg_is_well_formed_and_matches_modules() -> None:
    code = qr.encode(CONNECT_URL)
    markup = qr.to_svg(code, border=4, scale=3)
    root = ET.fromstring(markup)
    width = code.size + 8
    assert root.tag == f"{SVG}svg"
    assert root.get("viewBox") == f"0 0 {width} {width}"
    assert root.get("width") == root.get("height") == str(width * 3)
    assert root.get("shape-rendering") == "crispEdges"
    paths = root.findall(f"{SVG}path")
    assert len(paths) == 1
    assert root.find(f"{SVG}rect") is not None
    painted = [[False] * code.size for _ in range(code.size)]
    for x, y, length in re.findall(r"M(\d+) (\d+)h(\d+)v1h-\3z", paths[0].get("d", "")):
        for dx in range(int(length)):
            painted[int(y) - 4][int(x) - 4 + dx] = True
    assert painted == [list(row) for row in code.modules]


def test_svg_colors_are_escaped() -> None:
    root = ET.fromstring(qr.to_svg(qr.encode("x"), dark='"/><script/>', light="#fafafa"))
    path = root.find(f"{SVG}path")
    rect = root.find(f"{SVG}rect")
    assert path is not None and rect is not None
    assert path.get("fill") == '"/><script/>'
    assert rect.get("fill") == "#fafafa"


