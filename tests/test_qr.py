@pytest.mark.parametrize(
    "char, count, version",
    [
        ("1", 41, 1),  # Numeric capacity of 1-L.
        ("1", 42, 2),
        ("A", 25, 1),  # Alphanumeric capacity of 1-L.
        ("A", 26, 2),
        ("a", 17, 1),  # Byte capacity of 1-L.
        ("a", 18, 2),
        ("é", 8, 1),  # Byte mode counts UTF-8 bytes, not characters.
        ("é", 9, 2),
        ("1", 7089, 40),
        ("A", 4296, 40),
        ("a", 2953, 40),
    ],
)
def test_smallest_version_that_fits(char: str, count: int, version: int) -> None:
    # A fixed mask skips the penalty search; the version choice doesn't depend on it.
    assert qr.encode(char * count, error="L", mask=0).version == version


