#!/usr/bin/env python3
"""Regenerate checked-in built-in contracts (JSON, Swift, Kotlin) and native test fixtures.

The fixtures include mount transactions recorded from the host build of
the renderer core, so the Swift decoder is checked against the bytes the
apps receive.

The renderer core validates against the JSON contracts; Swift and Kotlin get
typed props, values, module adapters, and the fingerprint they were built from.
"""

import base64
import json
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal, NotRequired, TypedDict

import pythonnative  # noqa: F401  # Import the factories in a clean process.
from pythonnative.bridge import contract_document
from pythonnative.bridge.core import PROTOCOL_VERSION, Platform, decode_transaction, load_core
from pythonnative.sdk.builtins import write_builtin_contracts
from pythonnative.sdk.codegen import generate
from pythonnative.sdk.native_types import NativeTypes
from pythonnative.sdk.types import type_schema

ROOT = Path(__file__).resolve().parents[1]
NATIVE = ROOT / "src/pythonnative/native"
CORE_FIXTURES = NATIVE / "ios/Tests/PythonNativeKitTests/Fixtures"
SURFACE = 7


class NativeFixtureNote(TypedDict):
    """Exercise required null and nonrequired nullable fields in both compilers."""

    required: str | None
    optional: NotRequired[str | None]


@dataclass
class NativeFixtureDefault:
    """Exercise nested defaults and language-specific literal escaping."""

    note: NativeFixtureNote
    label: Literal['$total "quoted" \\path\n\x00\b', "ready"] = '$total "quoted" \\path\n\x00\b'
    nullable: str | None = None


def record_fixtures() -> dict[Path, str]:
    """Generate native test records from real Python annotations."""
    types = NativeTypes()
    types.types(type_schema(NativeFixtureDefault), "Fixture")
    return {
        NATIVE
        / "ios/Tests/PythonNativeKitTests/PNRecordFixtures.swift": (
            "// Generated by scripts/generate-native-contracts.py.\n"
            "import Foundation\nimport PythonNativeKit\n\n" + "\n".join(types.swift) + "\n"
        ),
        NATIVE
        / "android/src/test/java/com/pythonnative/generated/PNRecordFixtures.kt": (
            "// Generated by scripts/generate-native-contracts.py.\n"
            "package com.pythonnative.generated\n\n"
            "import org.json.JSONObject\nimport org.json.JSONArray\n\n" + "\n".join(types.kotlin) + "\n"
        ),
    }


def _op(op: Any) -> dict[str, Any]:
    out: dict[str, Any] = {"kind": op.kind, "tag": op.tag}
    if op.kind == "create":
        out.update(component=op.component, props=op.props)
    elif op.kind == "update":
        out.update(props=op.props, removed=list(op.removed), recreate=op.recreate)
    elif op.kind == "insert":
        out.update(parent=op.parent, index=op.index)
    elif op.kind == "frame":
        out.update(frame=list(op.frame))
    elif op.kind == "command":
        out.update(name=op.name, arguments=op.arguments, call_id=op.call_id)
    return out


def core_fixtures() -> dict[Path, str]:
    """Record mount transactions from the host core for the Swift decoder tests (and their contracts)."""
    document = contract_document()
    core = load_core()
    platform = Platform()
    platform.measure = lambda surface, tag, component, mode, props, w, wm, h, hm: (60.0, 16.0)
    core.reset()
    core.set_platform(platform)
    core.load_contracts(document, "host")
    revision = 0
    cases: list[dict[str, Any]] = []

    def drain(name: str) -> None:
        while True:
            taken = core.mount_next()
            if taken is None:
                return
            data, ident = taken
            transaction = decode_transaction(data)
            core.mount_finished(ident)
            cases.append(
                {
                    "name": name,
                    "bytes": base64.b64encode(data).decode(),
                    "surface": transaction.surface,
                    "revision": transaction.revision,
                    "id": transaction.id,
                    "ops": [_op(op) for op in transaction.ops],
                }
            )

    def commit(name: str, *ops: list[Any]) -> None:
        nonlocal revision
        envelope = {
            "version": PROTOCOL_VERSION,
            "application": "fixtures",
            "surface": SURFACE,
            "revision": revision + 1,
            "ops": list(ops),
            "layout": {"roots": [1], "width": 320, "height": 480, "selective": False},
        }
        ack = json.loads(core.commit(json.dumps(envelope)))
        assert ack["ok"], ack
        revision += 1
        drain(name)

    commit(
        "mount a tree",
        ["c", 1, "Column", {"flex": 1, "background_color": "#FFFFFF"}],
        ["c", 2, "View", {"padding": 8}],
        ["c", 3, "Text", {"text": "Héllo ✓", "font_size": 15.5, "max_lines": 2, "bold": True}],
        ["c", 4, "Button", {"title": "Go", "disabled": True}],
        ["c", 5, "View", {"background_color": "#FF0000", "width": 20, "height": 20, "transform": [{"rotate": 15}]}],
        ["i", 2, 3, 0],
        ["i", 1, 2, 0],
        ["i", 1, 4, 1],
        ["i", 1, 5, 2],
        ["c", 6, "TextInput", {"value": "abc"}],
        ["i", 1, 6, 3],
    )
    commit("update and remove props", ["u", 3, {"text": "Bye", "color": "#00FF00"}, ["max_lines", "bold"]])
    commit("move a child", ["i", 1, 5, 0])
    commit("delete a subtree", ["d", 3], ["d", 2])
    queued = json.loads(core.command(SURFACE, 6, "set_selection", json.dumps({"start": 1, "end": 2}), 41))
    assert queued.get("ok", True), queued
    drain("queue a command")
    core.reset()

    return {
        CORE_FIXTURES / "contracts.json": document,
        CORE_FIXTURES / "mount.json": json.dumps(cases, indent=1, ensure_ascii=False) + "\n",
    }


def main() -> None:
    """Generate both native libraries from the same Python definitions."""
    write_builtin_contracts()
    with tempfile.TemporaryDirectory(prefix="pn-contracts-") as folder:
        generate(folder)
        for extension, destination in (
            ("swift", NATIVE / "ios/Sources/PythonNativeKit/Generated"),
            ("kt", NATIVE / "android/src/main/java/com/pythonnative/generated"),
        ):
            for name in ("PNContracts", "NativeProps", "NativeModules", "NativeValues"):
                shutil.copyfile(Path(folder) / f"{name}.{extension}", destination / f"{name}.{extension}")
    for path, content in (record_fixtures() | core_fixtures()).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


if __name__ == "__main__":
    main()
